"""ICS pipeline + HF upload orchestration for Qwen3.5-2B.

Sequence:
1. Auth HF (token injected from local env via bridge)
2. Download model (~4 GB) -> upload snapshot to HF dataset repo
3. Run a 1-layer GPTQ smoke test (sanity, fail-fast)
4. Run full ICS+GPTQ pipeline in background subprocess
5. After each stage, upload to HF (incremental, so partial work survives)
6. Run PPL benchmark (dequantized model vs BF16 baseline)
7. Final: upload full artifact + write README + commit summary

Designed to be uploaded to /content/run_pipeline.py on Colab, then
launched as `nohup python3 -u /content/run_pipeline.py > /content/pipeline.log 2>&1 &`.
Then Mavis polls /content/pipeline.log.
"""
